-- ═══════════════════════════════════════════════════════════════
-- 社区演示问答
--
-- 背景：新部署环境的 question 表为空，社区问答页（/qa）显示
-- "还没有人提问"，体验上像未完工。本脚本补充一批与现有游戏
-- **真实关联**的演示问题。
--
-- 特性：
--   · 幂等：按标题判重，重复执行不会产生重复数据
--   · 关联真实数据：game_id 按游戏名匹配，游戏不存在则跳过该条
--   · 标题统一带 [演示] 前缀，便于识别与清理：
--       DELETE FROM question WHERE title LIKE '[演示]%';
--
-- 注意：评论（comment 表）未在此播种 —— 前端目前**没有**评论 UI
-- （只有后端 CommentController，页面未接入），灌了也看不见。
--
-- 执行：
--   docker exec -i game-prod-postgres psql -U <user> -d guide_platform < sql/seed-community-demo.sql
-- ═══════════════════════════════════════════════════════════════

INSERT INTO question (game_id, user_id, title, description, bounty_points, status, created_at, updated_at)
SELECT g.id, u.id, '[演示] ' || v.title, v.descr, v.bounty, 'OPEN',
       now() - (v.hours_ago || ' hours')::interval, now()
FROM (VALUES
  ('原神', '4.2 钟离还值得抽吗？',
   '手上有 90 抽，纠结要不要给钟离冲一命。目前队伍是雷神+菲谢尔，感觉缺个盾。', 20, 2),
  ('原神', '深渊 12 层怎么稳定满星？',
   '上半场用雷神队能过，下半场总是差 10 秒左右，想请教配队和循环思路。', 30, 5),
  ('英雄联盟', '现版本打野开局路线怎么选？',
   '现在野区经验改了以后老是被反，想问问大家开局是红开还是蓝开，什么时候该换野区。', 15, 8),
  ('黑神话：悟空', '第四章黄眉打不过，有什么技巧？',
   '第二阶段那个分身总是判断不出来，躲完一波就被连死。有没有比较稳的打法？', 25, 12),
  ('艾尔登法环', '新手初始职业选哪个比较好？',
   '第一次玩魂系，听说囚犯和武士比较友好，但又想玩法师，有点纠结。', 10, 20),
  ('崩坏：星穹铁道', '光锥没有专武该怎么替代？',
   '抽卡脸黑一直没出专武，四星光锥里哪些值得练？主要玩巡猎和智识。', 15, 26),
  ('明日方舟', '新手前期优先练哪些干员？',
   '刚过完第二章，资源很紧，怕练错干员浪费材料。求一个前中期通用的培养顺序。', 20, 30),
  ('塞尔达传说：王国之泪', '武器耐久太低怎么办？',
   '好武器用几下就碎了，有没有稳定获取或修复的办法？', 10, 36),
  ('DOTA 2', '辅助怎么在低分局带节奏？',
   '经常把线打好了但中期就崩，想请教视野和游走时机的把握。', 15, 44),
  ('永劫无间', '振刀总是掌握不好时机怎么办？',
   '知道要猜对方的出手节奏，但实战里反应不过来，有练习方法吗？', 10, 52)
) AS v(game_name, title, descr, bounty, hours_ago)
JOIN game g ON g.name = v.game_name
JOIN "user" u ON u.username = 'tester'
WHERE NOT EXISTS (
  SELECT 1 FROM question q WHERE q.title = '[演示] ' || v.title
);

-- ───── 校验输出 ─────
SELECT '演示问答' AS 类别, count(*) AS 条数 FROM question WHERE title LIKE '[演示]%';
