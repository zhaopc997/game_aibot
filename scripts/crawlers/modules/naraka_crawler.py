def crawl_and_sync_naraka(game_id=20):
    print(f'[Naraka] Preparing Comprehensive 32+ Heroes, Weapons & Souljades for Game {game_id} ...')

    conn = get_connection()
    try:
        with conn.cursor() as cur:
            # 清理旧有的重复格式名称
            cur.execute('''
                DELETE FROM game_character 
                WHERE game_id = %s 
                  AND name IN ('季沧海 (Ji Canghai)', '胡桃 (Kurumi)', '迦南 (Viper Canaan)')
            ''', (game_id,))
            conn.commit()
    finally:
        conn.close()

    characters = assemble_all_heroes()

    weapons = []
    for w in WEAPONS:
        short_w = w['name'].split()[0]
        weapons.append({
            'name': w['name'],
            'type': w['type'],
            'rarity': w['rarity'],
            'icon_url': f'/games/naraka_weapons/{short_w}.svg',
            'base_atk_curve': w['base_atk_curve'],
            'sub_stat': w['sub_stat'],
            'refinements': w['refinements'],
            'ascension_materials': w['ascension_materials'],
            'version': 'v2026'
        })

    artifacts = []
    for s in SOULJADES:
        short_s = s['name'].split()[2] if len(s['name'].split()) > 2 else s['name']
        artifacts.append({
            'name': s['name'],
            'rarity_min': 4,
            'rarity_max': 5,
            'icon_url': f'/games/souljades/{short_s}.svg',
            'two_piece_bonus': s['two_piece_bonus'],
            'four_piece_bonus': s['four_piece_bonus'],
            'pieces': s['pieces'],
            'rules_reference': s['rules_reference'],
            'version': 'v2026'
        })

    c_count = upsert_characters(game_id, characters)
    w_count = upsert_weapons(game_id, weapons)
    a_count = upsert_artifacts(game_id, artifacts)
    m_count = upsert_mechanics(game_id, MECHANICS)
    print(f'[Naraka] Ingested into Game {game_id}: {c_count} heroes, {w_count} weapons, {a_count} souljades, {m_count} mechanics.')


if __name__ == '__main__':
    crawl_and_sync_naraka(20)
