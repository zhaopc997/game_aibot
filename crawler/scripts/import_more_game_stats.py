def main():
    conn = psycopg2.connect(**PG)
    cur = conn.cursor()
    imported = 0
    for game_id, title, content in ADDITIONAL_ENTRIES:
        cur.execute("SELECT id FROM wiki_entry WHERE game_id = %s AND title = %s", (game_id, title))
        row = cur.fetchone()
        if row:
            cur.execute("UPDATE wiki_entry SET content = %s, last_updated = NOW() WHERE id = %s", (content, row[0]))
        else:
            cur.execute("INSERT INTO wiki_entry (game_id, title, content, last_updated) VALUES (%s, %s, %s, NOW())", (game_id, title, content))
        imported += 1
    conn.commit()
    conn.close()
    print(f"[import] 成功补充导入 {imported} 条热门游戏数值百科！")

if __name__ == '__main__':
    main()
